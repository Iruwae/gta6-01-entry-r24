import * as THREE from 'three';
import {makeRng} from './core/rng.js';
import {createBus} from './core/bus.js';
import {createInput} from './core/input.js';
import {createPlan,PLACES} from './world/cityPlan.js';
import {createCollision} from './world/collision.js';
import {createSky} from './world/sky.js';
import {createCityBuilder} from './world/cityBuilder.js';
import {stepCar,MAKES} from './vehicles/carPhysics.js';
import {createVehicleFleet} from './vehicles/vehicleFleet.js';
import {createTraffic} from './vehicles/traffic.js';
import {createPlayer} from './characters/player.js';
import {createPedestrians} from './characters/pedestrians.js';
import {WEAPONS,createLoadout} from './combat/weapons.js';
import {createCombat} from './combat/combat.js';
import {createWanted} from './police/wanted.js';
import {createDispatch} from './police/dispatch.js';
import {createMissionRunner} from './missions/missionRunner.js';
import {createActivities} from './missions/activities.js';
import {createRespect} from './missions/respect.js';
import {CREW} from './missions/story.js';
import {createSave} from './save/saveGame.js';
import {createHud} from './ui/hud.js';
import {createMenus} from './ui/menus.js';
import {createMinimap} from './ui/minimap.js';
import {createChaseCamera} from './camera/chaseCamera.js';
import {createRadio} from './audio/radio.js';
import {createEffects} from './effects/effects.js';
const canvas=document.getElementById('gl');
const renderer=new THREE.WebGLRenderer({canvas,antialias:true});
renderer.setPixelRatio(Math.min(window.devicePixelRatio||1,1.5));
renderer.setSize(window.innerWidth,window.innerHeight);
renderer.shadowMap.enabled=true;renderer.shadowMap.type=THREE.PCFSoftShadowMap;
renderer.toneMapping=THREE.ACESFilmicToneMapping;renderer.toneMappingExposure=1.12;
const scene=new THREE.Scene();
const camera=new THREE.PerspectiveCamera(62,window.innerWidth/window.innerHeight,0.1,6000);
camera.position.set(-350,26,60);
const game={renderer,scene,camera,seed:7,mode:'title',introShown:false,time:0,god:false,
 rng:makeRng(7),bus:createBus(),input:createInput(),standing:{}};
game.plan=createPlan(game.seed);game.collision=createCollision();
game.carPhysics={stepCar};
game.sky=createSky(game);
game.city=createCityBuilder(game);
game.effects=createEffects(game);
game.fleet=createVehicleFleet(game);
game.traffic=createTraffic(game);
game.player=createPlayer(game);
game.pedestrians=createPedestrians(game);
game.weapons={WEAPONS};game.loadout=createLoadout(game);
game.combat=createCombat(game);
game.wanted=createWanted(game);
game.dispatch=createDispatch(game);
game.missions=createMissionRunner(game);
game.activities=createActivities(game);
game.respect=createRespect(game);
game.crew=CREW;
game.save=createSave(game);
game.ui=createHud(game);
game.menus=createMenus(game);
game.minimap=createMinimap(game);
game.cameraRig=createChaseCamera(game);
game.radio=createRadio(game);
camera.snap=(pos,heading)=>game.cameraRig.snap(pos,heading);
game.fleetName=v=>MAKES[v.kind]?MAKES[v.kind].name:v.kind;
for(const d of['PANTAI MERPATI','PASAR SENJA','KOTA LAMA','MENARA KACA','KAMPUNG MANGGA','PELABUHAN','BUKIT HIJAU','PULAU KARANG'])game.standing[d]=50;
game.places=PLACES;
game.fixedStep=function(dt){game.time+=dt;
 game.sky.update(dt,game.player.position);
 game.city.update(dt,game.time);
 game.effects.update(dt);
 if(game.mode==='title'){game.traffic.update(dt);game.pedestrians.update(dt);game.fleet.update(dt,game.time);return}
 if(game.mode!=='play')return;
 game.player.update(dt,game.input);
 game.traffic.update(dt);game.pedestrians.update(dt);
 game.fleet.update(dt,game.time);
 game.wanted.update(dt);game.dispatch.update(dt);
 game.missions.update(dt);game.activities.update(dt);
 game.cameraRig.update(dt);
 if(game.input.hit('Escape')){game.mode='pause';game.menus.showPause()}
 if(game.input.hit('KeyQ'))game.radio.next();
 if(game.input.hit('Digit1'))game.loadout.select('fists');
 if(game.input.hit('Digit2'))game.loadout.select('bat');
 if(game.input.hit('Digit3'))game.loadout.select('pistol');
 if(game.input.hit('Digit4'))game.loadout.select('smg');
 if(game.input.hit('Digit5'))game.loadout.select('shotgun');
 if(game.input.hit('Digit6'))game.loadout.select('rifle');
 if(game.input.hit('Digit7'))game.loadout.select('rpg');
 if(game.input.hit('KeyZ'))game.ui.notice('Budi: Aku di jalan, Rak. Panggil saja kalau butuh jemputan.');
 if(game.input.hit('KeyX'))game.ui.notice('Wulan: Polisi ditandai di peta.');
 if(game.input.hit('KeyC')&&game.player.vehicle){game.player.vehicle.health=game.player.vehicle.maxHp;game.ui.notice('Agus: Mobil sudah diperbaiki.')}
 game.input.endFrame()};
game.render=function(){renderer.render(scene,camera)};
game.newGame=function(){const p=game.player;
 p.placeAt(-40,120,Math.PI/2);p.money=150000;p.health=100;p.armour=0;
 p.stats={kills:0,carsStolen:0,copsEvaded:0,earned:0,driven:0,fares:0,robbed:0,sold:0};
 game.respect.rp=0;game.wanted.set(0);game.time=0;
 game.loadout.give('pistol',36);game.loadout.select('pistol');
 const v=game.fleet.spawn('comet',-30,120,Math.PI/2);v.parked=false;
 game.menus.hideTitle();game.mode='play';game.introShown=true;
 game.missions.start('first-errand');
 game.ui.notice('Selamat datang di Teluk Senja, Rak.')};
game.bus.on('wasted',()=>{game.ui.titleCard('TERLUKA','Dirawat di Klinik Sehat · -Rp 300.000');
 game.player.money=Math.max(0,game.player.money-300000);
 game.player.health=100;game.player.armour=0;game.wanted.set(0);
 game.player.placeAt(200,300,0)});
window.__game=game;
game.menus.showTitle();
let last=performance.now(),acc=0;
function loop(now){requestAnimationFrame(loop);
 const dt=Math.min(0.05,(now-last)/1000);last=now;acc+=dt;
 let n=0;while(acc>=1/60&&n<4){game.fixedStep(1/60);acc-=1/60;n++}
 if(game.mode==='title'){const t=game.time;
  camera.position.set(-350+Math.sin(t*0.02)*40,26+Math.sin(t*0.05)*2,60);
  camera.lookAt(300,10,90)}
 game.ui.update(0.016);
 renderer.render(scene,camera)}
requestAnimationFrame(loop);
window.addEventListener('resize',()=>{camera.aspect=window.innerWidth/window.innerHeight;
 camera.updateProjectionMatrix();renderer.setSize(window.innerWidth,window.innerHeight)});
